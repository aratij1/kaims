import fs from 'node:fs';
import {expect,test} from '@playwright/test';
test.skip(!process.env.KAIOPS_LIVE_E2E,'Requires the live local stack');
test('verifies current health independently from RCA and persists the receipt',async({page})=>{
 test.setTimeout(120000);
 await page.goto('/');
 await page.getByLabel('Username').fill('admin');
 await page.getByLabel('Password').fill(process.env.KAIOPS_E2E_PASSWORD);
 await page.getByRole('button',{name:/sign in/i}).click();
 await expect(page.locator('.operations-home')).toBeVisible({timeout:45000});
 const id='b2306e7f-7319-4302-860d-bf9cbec068f5';
 await page.goto(`/incidents/${id}`);
 await page.locator('.ic-investigation-history').evaluate(element=>element.setAttribute('open',''));
 const panel=page.getByRole('article',{name:'Independent current recovery'});
 await expect(panel).toBeVisible({timeout:30000});
 const response=page.waitForResponse(r=>r.url().includes(`/incidents/${id}/recovery-observation`)&&r.request().method()==='POST',{timeout:35000});
 await panel.getByRole('button',{name:'Verify current recovery'}).click();
 const received=await response;expect(received.status()).toBe(200);
 const raw=await received.json();const observed=raw.data||raw;
 expect(observed.corrective_execution_performed).toBe(false);
 expect(observed.closes_incident).toBe(false);
 expect(observed.checks).toHaveLength(6);
 for(const check of observed.checks) await expect(panel).toContainText(`${check.kind.replaceAll('_',' ')}: ${check.status}`);
 await expect(panel).toContainText('does not execute remediation or close the incident');
 if(observed.status==='verified') await expect(page.locator('#incident-rca')).toContainText('Current health independently verified');
 const workspaceResponse=page.waitForResponse(r=>r.url().includes(`/incidents/${id}/command`)&&r.status()===200,{timeout:45000});
 await page.reload();
 const rawWorkspace=await (await workspaceResponse).json();const workspace=rawWorkspace.data||rawWorkspace;
 expect(workspace.operations.recovery_observation.observation_id).toBe(observed.observation_id);
 expect(workspace.operations.lifecycle_state).not.toBe('closed');
 fs.mkdirSync('../../artifacts/self-healing-research',{recursive:true});
 fs.writeFileSync('../../artifacts/self-healing-research/browser-observation.json',JSON.stringify({incident_id:id,status:observed.status,receipt:observed.observation_id,checks:observed.checks.map(c=>({kind:c.kind,status:c.status,samples:c.samples.length})),lifecycle:workspace.operations.lifecycle_state,rca_status:workspace.operations.investigation_workspace.rca.status,execution_status:workspace.operations.execution.status},null,2));
});
