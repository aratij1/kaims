import { useEffect, useRef } from "react";
import { FileText, X } from "lucide-react";
import "./KnowledgeDocumentReader.css";

type OperationalDocument = {
  title: string;
  document_kind?: string;
  document_version?: number;
  content?: string;
  source_ref?: string;
  content_checksum?: string;
  metadata?: { service?: string; environment?: string; incident_id?: string; source_uris?: string[] };
};

export default function KnowledgeDocumentReader({ document: selected, onClose }: {
  document: OperationalDocument;
  onClose: () => void;
}) {
  const dialogRef = useRef<HTMLDialogElement>(null);

  useEffect(() => {
    const dialog = dialogRef.current;
    if (!dialog) return;
    const previousOverflow = window.document.body.style.overflow;
    if (!dialog.open) dialog.showModal();
    window.document.body.style.overflow = "hidden";
    return () => {
      window.document.body.style.overflow = previousOverflow;
    };
  }, []);

  return <dialog ref={dialogRef} className="knowledge-document-dialog"
    aria-labelledby="operational-document-title" aria-modal="true" onClose={onClose}>
    <section className="knowledge-document-reader">
      <header>
        <div>
          <span className="discovery-eyebrow">{String(selected.document_kind || "document").replaceAll("_", " ")}{selected.document_version ? ` · v${selected.document_version}` : ""}</span>
          <h3 id="operational-document-title">{selected.title}</h3>
          <p>{selected.metadata?.service || "Unknown service"} · {selected.metadata?.environment || "Unknown environment"} · Incident {selected.metadata?.incident_id || "not linked"}</p>
        </div>
        <button type="button" className="button-secondary" autoFocus aria-label="Close document"
          onClick={() => dialogRef.current?.close()}><X size={16} aria-hidden="true" /> Close</button>
      </header>
      <div className="knowledge-document-body">
        {selected.content ? <pre>{selected.content}</pre> : <div className="ai-hub-empty">
          <FileText size={25} aria-hidden="true" /><strong>Document content is not available</strong>
          <span>Refresh the report to load content generated by the current worker version.</span>
        </div>}
      </div>
      <footer>
        <span>Source <code>{selected.source_ref || "not recorded"}</code></span>
        <span>Checksum <code>{selected.content_checksum || "not recorded"}</code></span>
        {selected.metadata?.source_uris?.length ? <nav aria-label="Document evidence sources">
          {selected.metadata.source_uris.map(uri => <a key={uri} href={uri} target="_blank" rel="noreferrer">Evidence source</a>)}
        </nav> : null}
      </footer>
    </section>
  </dialog>;
}
